import { NextRequest, NextResponse } from 'next/server';
import { store } from '@/lib/data/store';
import { crmConfig, isCrmConfigured } from '@/config/crm.config';

export async function GET() {
  try {
    const logs = store.getCrmSyncLogs().slice(0, 30);
    const leads = store.getLeads().slice(0, 30);

    const totalLeads = leads.length;
    const syncedCount = leads.filter((l) => l.crmSyncStatus === 'SYNCED').length;
    const pendingCount = leads.filter((l) => l.crmSyncStatus === 'PENDING').length;
    const failedCount = leads.filter((l) => l.crmSyncStatus === 'FAILED').length;

    return NextResponse.json({
      success: true,
      config: {
        provider: crmConfig.provider,
        apiEndpoint: crmConfig.apiEndpoint ? `${crmConfig.apiEndpoint.substring(0, 24)}...` : 'Not configured',
        isConfigured: isCrmConfigured(),
        hasApiKey: !!crmConfig.apiKey,
        hasWebhookSecret: !!crmConfig.webhookSecret,
        retryAttempts: crmConfig.retryAttempts,
      },
      stats: {
        totalLeads,
        syncedCount,
        pendingCount,
        failedCount,
        syncSuccessRate: totalLeads > 0 ? `${Math.round((syncedCount / totalLeads) * 100)}%` : '100%',
      },
      recentLogs: logs,
    });
  } catch (err: any) {
    return NextResponse.json({ success: false, error: err.message }, { status: 500 });
  }
}

export async function POST(req: NextRequest) {
  try {
    const body = await req.json().catch(() => ({}));
    const { action, logId } = body;

    // One-click Retry failed log
    if (action === 'RETRY' && logId) {
      const result = await store.retryCrmSync(logId);
      return NextResponse.json({
        success: result.success,
        message: result.success ? 'Lead successfully retried & synced to CRM!' : 'Retry failed. Check CRM endpoint status.',
        log: result.log,
      });
    }

    // Ping / Test connection with mock test lead
    if (action === 'TEST_PING') {
      const testLead = store.createLead({
        name: 'Test CRM Probe Lead',
        phone: '+91 98200 00000',
        email: 'probe.test@prosify.in',
        source: 'WEBSITE',
        requirement: 'Webhook Connection Probe',
        notes: 'Automated test lead generated by Admin Suite to verify webhook endpoint health.',
      });

      const result = await store.dispatchLeadToCrm(testLead.id);
      return NextResponse.json({
        success: result.success,
        message: result.success
          ? 'Probe successfully delivered to external CRM!'
          : 'CRM returned failure or no endpoint configured in .env. Stored in local fallback.',
        log: result.log,
        attempts: result.attempts,
      });
    }

    return NextResponse.json({ success: false, error: 'Invalid action' }, { status: 400 });
  } catch (err: any) {
    return NextResponse.json({ success: false, error: err.message }, { status: 500 });
  }
}
